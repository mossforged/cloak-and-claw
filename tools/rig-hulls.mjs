// Rig hulls (T024): the outline of every rig drawing (parts, swaps, held items) as a convex hull in its own image px,
// for the floor-line rule (render/floor.js: a foot's lowest point, a lying body's lowest point) and the stretch test.
// Usage: node tools/rig-hulls.mjs   (rewrites src/data/rigs/hulls.js from the images the rigs name; run after an import)
import { writeFileSync } from 'node:fs';
import { RIGS } from '../src/data/rigs/index.js';
import { RAT_A010 } from '../src/data/rigs/a010/index.js';   // T026: the old rat, kept for the viewer's compare slot
import { readAlpha } from './bench/png.mjs';

// Monotone-chain hull of the opaque pixels' corners, simplified (Douglas-Peucker, eps image px).
export function hullOf({ w, h, alpha }, eps = 1) {
  const pts = [];
  for (let y = 0; y < h; y++) {
    let a = -1, b = -1;
    for (let x = 0; x < w; x++) if (alpha[y * w + x] > 127) { if (a < 0) a = x; b = x; }
    if (a >= 0) pts.push([a, y], [b + 1, y], [a, y + 1], [b + 1, y + 1]);
  }
  pts.sort((p, q) => p[0] - q[0] || p[1] - q[1]);
  const cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
  const half = (list) => { const out = []; for (const p of list) { while (out.length > 1 && cross(out.at(-2), out.at(-1), p) <= 0) out.pop(); out.push(p); } out.pop(); return out; };
  const hull = [...half(pts), ...half([...pts].reverse())];
  const keep = new Array(hull.length).fill(false);
  const dp = (i, j) => {   // on the closed ring, between i and j
    let best = -1, k = -1;
    for (let n = i + 1; n < j; n++) {
      const [a, b, p] = [hull[i], hull[j % hull.length], hull[n]], L = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
      const d = Math.abs((b[0] - a[0]) * (a[1] - p[1]) - (a[0] - p[0]) * (b[1] - a[1])) / L;
      if (d > best) { best = d; k = n; }
    }
    if (best > eps) { keep[k] = true; dp(i, k); dp(k, j); }
  };
  keep[0] = true;
  const far = hull.reduce((m, p, i) => (Math.hypot(p[0] - hull[0][0], p[1] - hull[0][1]) > Math.hypot(hull[m][0] - hull[0][0], hull[m][1] - hull[0][1]) ? i : m), 0);
  keep[far] = true; dp(0, far); dp(far, hull.length);
  return hull.filter((_, i) => keep[i]);
}

export function imagesOf(rig) {
  const out = new Set();
  for (const p of Object.values(rig.parts)) {
    out.add(p.img);
    for (const s of Object.values(p.swaps ?? {})) out.add(s.img);
  }
  return [...out];
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const all = [...new Set([...Object.values(RIGS), ...Object.values(RAT_A010)].flatMap(imagesOf))].sort();
  const lines = ['// GENERATED by tools/rig-hulls.mjs (T024): convex hull of each rig drawing, its own image px. Do not edit.', 'export default {'];
  for (const img of all) lines.push(`  '${img}': ${JSON.stringify(hullOf(readAlpha(img)))},`);
  lines.push('};', '');
  writeFileSync('src/data/rigs/hulls.js', lines.join('\n'));
  console.log(`wrote src/data/rigs/hulls.js (${all.length} drawings)`);
}

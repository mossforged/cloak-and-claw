"""Gear + mask importer (T019). Reads an overlay manifest (A011's rig-source.json: `overlays`, `masks`) that extends a
base rig source (A010's parts/swaps, all on one canvas), plus its compatibility.json, and writes:
  - every overlay keyed and trimmed at the base rig's --scale into --art/gear/, with its offset in the image px of the
    part it rides (overlays share the parts' canvas at [0,0], so offset = (overlay trim corner - part trim corner) * scale)
  - every non-empty grey mask cropped to the trim box of the image it masks (part, swap or overlay) and scaled the same,
    so it lines up pixel for pixel with the game image, into --art/masks/
  - src/data/rigs/<id>-gear.js: OVERLAYS, VIEWS (compatibility) and MASKS (game image path -> { cloth, fur } paths
    plus each mask's mean lightness and saturation of what it selects, the tint's reference: render/looks.js)
Usage: python3 tools/gear_from_source.py assets/source/A011-rat-raider-finishing/rig-source.json --id rat-raider
       [--art assets/art/enemies/rat-raider] [--out src/data/rigs/rat-raider-gear.js] [--scale 0.4]"""
import argparse, json, os, sys
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from key_green import key  # noqa: E402


def trim_box(path):
    """The trim box key_green.key() would use for this source image (alpha > 20)."""
    img = Image.open(path)
    if img.mode == "RGBA" and img.getchannel("A").getextrema()[0] < 255:
        alpha = np.asarray(img.getchannel("A")).astype(np.float32)
    else:
        a = np.asarray(img.convert("RGB")).astype(np.float32)
        spill = a[..., 1] - np.maximum(a[..., 0], a[..., 2])
        alpha = np.clip(1 - (spill - 25) / 70, 0, 1) * 255
    return Image.fromarray(alpha.astype(np.uint8)).point(lambda v: 255 if v > 20 else 0).getbbox()


def hsl_means(rgb_path, box, mask):
    """Mask-weighted mean HSL lightness and saturation (0..1) of the source pixels the mask selects."""
    a = np.asarray(Image.open(rgb_path).convert("RGB").crop(box)).astype(np.float32) / 255
    mx, mn = a.max(axis=2), a.min(axis=2)
    L = (mx + mn) / 2
    S = np.where(mx > mn, (mx - mn) / np.maximum(1 - np.abs(2 * L - 1), 1e-6), 0)
    w = mask.astype(np.float32) / 255
    mean = lambda v: round(float((v * w).sum() / max(w.sum(), 1e-6)), 3)
    return mean(L), mean(S)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("source")
    ap.add_argument("--id", required=True)
    ap.add_argument("--art")
    ap.add_argument("--out")
    ap.add_argument("--scale", type=float, default=0.4)
    a = ap.parse_args()
    folder = os.path.dirname(a.source)
    src = json.load(open(a.source))
    views = json.load(open(os.path.join(folder, "compatibility.json")))
    art = (a.art or f"assets/art/enemies/{a.id}").rstrip("/")
    out = a.out or f"src/data/rigs/{a.id}-gear.js"
    s = a.scale
    for d in ("gear", "masks"):
        os.makedirs(f"{art}/{d}", exist_ok=True)

    # every drawing a mask can belong to: name -> (source path, trim box, game image path)
    imgs = {}
    for name, p in src["parts"].items():
        path = os.path.join(folder, p["img"])
        imgs[name] = (path, trim_box(path), f"{art}/rig/{name}.png")
    for name, sw in src.get("swaps", {}).items():
        path = os.path.join(folder, sw["img"])
        imgs[name] = (path, trim_box(path), f"{art}/rig/{name}.png")

    overlays = {}
    for name, o in src["overlays"].items():
        path = os.path.join(folder, o["img"])
        dst = f"{art}/gear/{name}.png"
        if trim_box(path) is None:   # intentionally blank (rear eyepatch / scar: the face is hidden)
            overlays[name] = {"img": None, "on": o["on"], "order": o["band"]}
            continue
        _, box = key(path, dst, None, s)
        base = imgs[o["on"]][1]
        overlays[name] = {"img": dst, "on": o["on"], "order": o["band"],
                          "offset": [round((box[0] - base[0]) * s, 2), round((box[1] - base[1]) * s, 2)]}
        imgs[name] = (path, box, dst)

    masks = {}
    for name, m in src["masks"].items():
        if m.get("empty"):
            continue
        kind = "fur" if name.endswith("-fur-mask") else "cloth"
        path, box, game = imgs[m["on"]]
        crop = Image.open(os.path.join(folder, m["img"])).convert("L").crop(box)
        size = Image.open(game).size
        dst = f"{art}/masks/{name}.png"
        crop.resize(size, Image.LANCZOS).save(dst, optimize=True)
        masks.setdefault(game, {})[kind] = dst
        masks[game][kind + "L"], masks[game][kind + "S"] = hsl_means(path, box, np.asarray(crop))
        print(dst, size)

    js = lambda v: json.dumps(v, separators=(", ", ": ")).replace('"', "'")
    lines = [f"// Rat gear overlays and recolour masks (T019), generated by tools/gear_from_source.py from {a.source}.",
             "// OVERLAYS: drawing name -> image, the part it rides (`on`), draw order (band) and offset in that part's own image px",
             "//   (overlays share the parts' canvas, so they ride the part whichever swap it shows).",
             "// VIEWS: gear group -> { on, views: the part's current drawing (swap name, or the part's own name) -> overlay }.",
             "// MASKS: game image path -> grey masks (white = recolour) for cloth and fur, with the mean lightness",
             "//   and saturation of the pixels each selects (clothL/S, furL/S: what a tint's target colour is measured against). Do not edit by hand.",
             "export const OVERLAYS = {"]
    lines += [f"  '{n}': {js(o)}," for n, o in overlays.items()]
    lines += ["};", "", "export const VIEWS = {"]
    lines += [f"  '{n}': {js({'on': g['on'], 'views': g['views']})}," for n, g in views.items()]
    lines += ["};", "", "export const MASKS = {"]
    lines += [f"  '{n}': {js(m)}," for n, m in masks.items()]
    lines += ["};", ""]
    open(out, "w").write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()

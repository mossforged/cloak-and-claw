// T028 r4: pins the user's grip lines (docs/design/rigs/grip-lines-rat.json, fractions of each game image) to the
// shared A017 canvas, so a re-import that changes a drawing's trim box (A023 round 4's longer wrist ends) never moves
// them. Run once, on the images the user drew on (A023 round 3 import):
//   node tools/grip-lines-pin.mjs > src/data/rigs/rat-raider-grip-lines.js
// Hand and arm-key lines: image px -> part px (+ swap offset; the rat's swaps are unscaled) -> canvas (pivot_canvas +
// (part px - pivot px) / CUT, CUT = the importer's 0.4). Items: image px straight (the item images are the game's own).
// A021 items: fractions of the keyed source trimmed to its alpha box; tools/a021-import.sh cuts the game images the same
// way, so the fractions hold on them (applied in rat-raider-grip-lines.js against each image's size).
import { readFileSync } from 'node:fs';
import rig from '../src/data/rigs/rat-raider.js';

const CUT = 0.4;
// A018 / A022 / A023 pivots on the A017 canvas (rig-source.json: unchanged in every round)
const PIVOT = { 'hand-near': [401, 1440], 'hand-far': [1107, 1451], 'arm-near-upper': [555, 1174], 'arm-far-upper': [960, 1179] };
const src = JSON.parse(readFileSync(new URL('../docs/design/rigs/grip-lines-rat.json', import.meta.url))).lines;
const r = (v) => Math.round(v * 100) / 100, pt = (p) => `[${r(p[0])}, ${r(p[1])}]`, fr = (p) => `[${p[0]}, ${p[1]}]`;
const owner = (name) => Object.entries(rig.parts).find(([, p]) => p.swaps?.[name]);
const out = [], items = [];
for (const [name, L] of Object.entries(src)) {
  const px = (f) => [f[0] * L.w, f[1] * L.h];
  if (L.kind === 'weapon') {
    items.push(`  '${name}': { size: [${L.w}, ${L.h}], a: ${fr(L.a)}, b: ${fr(L.b)}${L.c ? `, c: ${fr(L.c)}` : ''} },`);
    continue;
  }
  const [part, p] = owner(name), off = p.swaps[name].offset ?? [0, 0];
  const canvas = (f) => { const q = px(f); return [PIVOT[part][0] + (q[0] + off[0] - p.pivot[0]) / CUT, PIVOT[part][1] + (q[1] + off[1] - p.pivot[1]) / CUT]; };
  out.push(`  '${name}': { part: '${part}', a: ${pt(canvas(L.a))}, b: ${pt(canvas(L.b))} },`);
}
console.log(`// GENERATED by tools/grip-lines-pin.mjs (T028 r4) from docs/design/rigs/grip-lines-rat.json: the user's grip lines.
// a = where the handle enters the fist at the pommel end, b = where it leaves toward the blade (grip centre = midpoint,
// handle direction = a -> b). DRAWINGS: A017 canvas px (pinned on the A023 round 3 images the user drew on; a re-import
// moves pivots and offsets, never these). ITEMS: fractions of each item image (a = where the fist holds, b = further along
// toward the head, c = the second hand); size = the image the user drew on. Read through data/rigs/grip-lines.js.
export const CUT = ${CUT};
export const PIVOT = ${JSON.stringify(PIVOT).replace(/,/g, ', ').replace(/:/g, ': ')};
export const DRAWINGS = {
${out.join('\n')}
};
export const ITEMS = {
${items.join('\n')}
};`);

// T035: which of the raider's pose keys need drawings rat v3 lacks (they play on v3's three-quarter drawings meanwhile):
// other views (S, F, BQ, B, H, LB), other heads, hand drawings (grips, open, palms), whole-limb keys, foot keys, and the
// items held on fists v3 has no grip lines for. Writes docs/screens/T035/missing.md (or the path given).
// T039: v3 has A028's hands, heads and feet (the raider's names), so only other views, whole-limb drawings and drawings
// A028 didn't make are left; held items: which v3 hand drawing holds each, on whose lines (rat-v3-grip-lines.js).
// Usage: node tools/v3-missing.mjs [out.md]
import { writeFileSync } from 'node:fs';
import { FIGHTERS } from '../src/data/fighters/index.js';
import { ITEMS } from '../src/data/items/index.js';
import V3, { V3_SPEARMAN } from '../src/data/rigs/rat-v3.js';
import { SOURCE } from '../src/data/rigs/rat-v3-grip-lines.js';
import { strapRig } from '../src/render/strap.js';

const out = process.argv[2] ?? 'docs/screens/T035/missing.md', P = V3.poses, def = FIGHTERS['rat-raider'];
const kind = (part, name) => (/^head/.test(part) ? 'head' : /^hand/.test(part) ? 'hand drawing' : V3.parts[part] && /^(arm|leg)/.test(part) && /(cocked|raised|smear|mouth|guard|kneel|kneeup|folded)/.test(name) ? 'whole-limb drawing'
  : /^foot/.test(part) ? 'foot drawing' : 'drawing');
const FIST = /^hand-(near|far)-fist$/;
// T039: how v3 holds an item: the drawing (the grip slot's heldHand, the two-hand / bow grips' second hands), or why not
function holdOf(id, strap) {
  const it = ITEMS[id];
  if (strap) return strapRig(V3, it) !== V3 ? 'strapped on hand-far-shield' : '**not held**: hand-far-shield has no grip line yet (Art drew none; the user\'s lines will add it)';
  const slot = V3.slots?.[it?.grip];
  if (!slot || !V3.itemLines?.[id]) return '**not held** (no slot / item line)';
  const g = V3.grips?.[it.grip], hands = [slot.parent === 'hand-near' ? V3.heldHand['hand-near'] : 'hand-far-grip', ...Object.values(g?.swap ?? {}).filter((n) => !n.startsWith('hand-near-grip'))];
  return `held: ${[...new Set(hands)].join(' + ')}`;
}
function missing(pose) {
  const out = [];
  const sw = { ...(pose?.swap ?? {}) };
  for (const s of pose?.swapPhase ?? []) sw[s.part + ' (in step)'] = s.swap;
  for (const [k, v] of Object.entries(pose?.view ?? {})) if (v !== 'Q') out.push(`view ${k} ${v}`);
  for (const [part0, name] of Object.entries(sw)) {
    const part = part0.replace(' (in step)', '');
    if (FIST.test(name)) continue;   // v3's own hands are fists
    if (!V3.parts[part]?.swaps?.[name]) out.push(`${kind(part, name)} ${name}`);
  }
  for (const [part, band] of Object.entries(pose?.order ?? {})) out.push(`band ${part} ${band} (made for ${sw[part] ?? 'its old drawing'})`);
  if (pose?.carry) out.push(`carried ${pose.carry} (carry socket)`);
  return out;
}
const rows = [];
const add = (move, key, pose) => { const m = missing(pose); if (m.length) rows.push([move, key, m.join('; ')]); };
for (const [k, v] of Object.entries(P)) if (!['timing', 'stance', 'moves'].includes(k) && v && typeof v === 'object') add(k, '(pose)', v);
const moves = { ...P.moves, ...Object.fromEntries(Object.entries(V3_SPEARMAN.poses.moves).filter(([k]) => !P.moves[k]).map(([k, M]) => [`${k} (spearman)`, M])) };
for (const [mk, M] of Object.entries(moves)) {
  add(mk, 'windup', M.windup);
  (Array.isArray(M.through) ? M.through : M.through ? [M.through] : []).forEach((x, i) => add(mk, Array.isArray(M.through) ? `through.${i + 1}` : 'through', x));
  add(mk, 'strike', M.strike);
  if (M.recover) add(mk, 'recover', M.recover);
}
const sp = FIGHTERS['rat-spearman'];
const items = [[`all`, def.art.held ?? def.kit, 'its own item'], ['spearman (all)', sp.kit ?? sp.art.held, 'the spearman\'s own item']];
for (const [mk, m] of Object.entries({ ...def.moves, ...def.rehearsal })) {
  if (m.item) items.push([mk, m.item, 'the move\'s own item']);
  if (m.strap) items.push([mk, m.strap, 'strapped on the far hand']);
}
const lines = ['# T039: rat v3 keys that need drawings v3 still lacks', '',
  `GENERATED by \`node tools/v3-missing.mjs\` from the raider's poses (rigs/rat-raider-poses.js and its move files). T039: v3 now has A028's hand, head and foot drawings under the raider's names, so a key naming one shows it; what is left is other views (S, F, BQ, B, H, LB), whole-limb drawings and the drawings A028 didn't make. Each such key plays on v3's three-quarter drawings, retargeted by position inside the user's limits. (A key's \`hand-*-fist\` is not listed: v3's own hands are fists.)`, '',
  `${rows.length} keys.`, '', '| Move | Key | Missing on v3 |', '|---|---|---|', ...rows.map((r) => `| ${r.join(' | ')} |`), '',
  '## Held items', '', `v3 holds its items on ${SOURCE === 'user' ? "the user's grip lines (docs/design/rigs/grip-lines-rat-v3.json)" : "Art's A028 handle lines (provisional, until the user's lines arrive: tools/v3-grip-lines.mjs, then re-run this)"}. Poses that open the hand (knockdown, grabbed, thrown, down, held) show the item on the open hand, as the raider does.`, '',
  '| Move | Item | | v3 |', '|---|---|---|---|', ...[...new Map(items.map((r) => [r.join(), r])).values()].map(([m, it, why]) => `| ${m} | ${ITEMS[it]?.name ?? it} | ${why} | ${holdOf(it, /strapped/.test(why))} |`), ''];
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${rows.length} keys, ${items.length} item holds`);

// T039: writes src/data/rigs/rat-v3-grip-lines.js, the grip lines rat v3 holds its items by, in the format of
// rat-raider-grip-lines.js (read through data/rigs/grip-lines.js withGripLines). Two sources, the user's winning:
//   1. docs/design/rigs/grip-lines-rat-v3.json, the user's own lines (the "Rat v3 Grip Lines" page; the lead drops it in):
//      the format of grip-lines-rat.json (fractions a / b / c of each image, w / h its size) plus each hand drawing's
//      `origin` (canvas px of the image's top-left) and `scale` (image px per canvas px: 0.4 for the game's cuts), so a
//      hand's point on the A017 canvas = origin + (fraction x [w, h]) / scale. Its weapon lines replace the raider's.
//   2. Until then, Art's `handleLine` on A028's grip hands (assets/source/A028-rat-v3-kit/rig-source.json, canvas px).
//      Art's lines have no direction, so each is run toward the item's head as the raider's line for the same hand runs
//      (the end whose direction is nearer the raider's); where the two ends are equally far from it (Art's line square
//      to the raider's) the end in TIE below, measured by tools/v3-grip-ends.mjs (the one that holds the item nearer the
//      way the raider holds it over the clips). Items keep the raider's lines (same images).
// Usage: node tools/v3-grip-lines.mjs [--art] [--flip <hand,...>] [--out <file>] [--user <json>]
//   --art: Art's lines even when the user's file exists; --flip: run those hands' lines the other way (end tests);
//   --user: another user file (tests).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import * as RAIDER from '../src/data/rigs/rat-raider-grip-lines.js';

const arg = (k) => { const i = process.argv.indexOf(k); return i < 0 ? null : process.argv[i + 1]; };
const USER = arg('--user') ?? 'docs/design/rigs/grip-lines-rat-v3.json', ART = 'assets/source/A028-rat-v3-kit/rig-source.json';
const out = arg('--out') ?? 'src/data/rigs/rat-v3-grip-lines.js', flip = new Set((arg('--flip') ?? '').split(',').filter(Boolean));
const J = JSON.parse(readFileSync('docs/design/rigs/rat-v3-joints-v4.json', 'utf8')).joints;
const PIVOT = { 'hand-near': J['wrist-near'].world, 'hand-far': J['wrist-far'].world };
// Art's lines square to the raider's (both ends 90 degrees off): the end toward the item's head, from tools/v3-grip-ends.mjs
// ('first' = Art's first point is the pommel end, 'second' = his second). T039 measured over 5779 frames: near grip
// pommel at the top (head down) 72 deg mean off the raider's item vs 114 the other way; near overhand as drawn 46 vs 134.
const TIE = { 'hand-near-grip': 'first', 'hand-near-grip-overhand': 'first' };
const r = (v) => Math.round(v * 100) / 100, pt = (p) => `[${r(p[0])}, ${r(p[1])}]`, fr = (p) => `[${p[0]}, ${p[1]}]`;
const deg = (a, b) => Math.atan2(b[1] - a[1], b[0] - a[0]) * 180 / Math.PI;
const off = (x, y) => Math.abs(((x - y + 540) % 360) - 180);

const user = !process.argv.includes('--art') && existsSync(USER);
const hands = [], items = [], notes = [];
if (user) {
  const src = JSON.parse(readFileSync(USER, 'utf8')).lines;
  for (const [name, L] of Object.entries(src)) {
    if (L.kind === 'weapon') { items.push(`  '${name}': { size: [${L.w}, ${L.h}], a: ${fr(L.a)}, b: ${fr(L.b)}${L.c ? `, c: ${fr(L.c)}` : ''} },`); continue; }
    if (!name.startsWith('hand-') || !L.origin || !L.scale) { notes.push(`${name}: skipped (not a hand line with origin and scale)`); continue; }
    const part = name.startsWith('hand-near') ? 'hand-near' : 'hand-far';
    const canvas = (f) => [L.origin[0] + (f[0] * L.w) / L.scale, L.origin[1] + (f[1] * L.h) / L.scale];
    let [a, b] = [canvas(L.a), canvas(L.b)];
    if (flip.has(name)) [a, b] = [b, a];
    hands.push(`  '${name}': { part: '${part}', a: ${pt(a)}, b: ${pt(b)} },`);
  }
} else {
  const S = JSON.parse(readFileSync(ART, 'utf8')).swaps;
  for (const [name, s] of Object.entries(S)) {
    if (!s.handleLine || s.layer === 'behind-item') continue;   // the under piece shares its face's line
    const old = RAIDER.DRAWINGS[name], [p, q] = s.handleLine, d1 = deg(p, q), d0 = old && deg(old.a, old.b);
    const e1 = old ? off(d1, d0) : 0, e2 = old ? off(d1 + 180, d0) : 0;
    let first = Math.abs(e1 - e2) > 20 ? e1 < e2 : (TIE[name] ?? 'first') === 'first';
    if (flip.has(name)) first = !first;
    const [a, b] = first ? [p, q] : [q, p];
    notes.push(`${name}: ${pt(a)} -> ${pt(b)} (${r(deg(a, b))} deg; the raider's ${old ? r(d0) : '-'} deg${Math.abs(e1 - e2) > 20 ? '' : ', a tie: TIE'}${flip.has(name) ? ', flipped' : ''})`);
    hands.push(`  '${name}': { part: '${s.replaces}', a: ${pt(a)}, b: ${pt(b)} },`);
  }
}
const text = `// GENERATED by tools/v3-grip-lines.mjs (T039) from ${user ? USER + ": the user's own grip lines" : ART + ": Art's handleLine on A028's grip hands (provisional, until the user's lines arrive as " + USER + ', then re-run)'}.
// a = where the handle enters the fist at the pommel end, b = where it leaves toward the item's head (grip centre = the
// midpoint, handle direction = a -> b). DRAWINGS: A017 canvas px; PIVOT: v3's wrist points (the user's fitted joints).
${notes.map((n) => `//   ${n}`).join('\n')}
// ITEMS: ${items.length ? "the user's item lines" : "the raider's (rat-raider-grip-lines.js: the same item images)"}. Read through data/rigs/grip-lines.js.
${items.length ? '' : "import { ITEMS as RAIDER_ITEMS } from './rat-raider-grip-lines.js';\n"}export const SOURCE = '${user ? 'user' : 'art'}';
export const CUT = 0.4;
export const PIVOT = ${JSON.stringify(PIVOT).replace(/,/g, ', ').replace(/:/g, ': ')};
export const DRAWINGS = {
${hands.join('\n')}
};
export const ITEMS = ${items.length ? `{\n${items.join('\n')}\n}` : 'RAIDER_ITEMS'};
`;
writeFileSync(out, text);
console.log(`wrote ${out} (${user ? 'user' : 'art'} lines: ${hands.length} hands)`);
for (const n of notes) console.log(' ', n);
